-- Marks. Component-wise, because NCTB requires separate CQ/MCQ pass marks —
-- a student can total 45 and still fail on the CQ component alone.
CREATE TABLE exam_marks (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id         uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  exam_subject_id   uuid NOT NULL REFERENCES exam_subjects(id) ON DELETE CASCADE,
  student_id        uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  academic_year_id  uuid NOT NULL REFERENCES academic_years(id) ON DELETE CASCADE,

  cq_marks          numeric(5,2) CHECK (cq_marks >= 0),
  mcq_marks         numeric(5,2) CHECK (mcq_marks >= 0),
  practical_marks   numeric(5,2) CHECK (practical_marks >= 0),
  ca_marks          numeric(5,2) CHECK (ca_marks >= 0),
  total_marks       numeric(6,2) GENERATED ALWAYS AS
                      (COALESCE(cq_marks,0) + COALESCE(mcq_marks,0)
                       + COALESCE(practical_marks,0) + COALESCE(ca_marks,0)) STORED,

  is_absent         boolean NOT NULL DEFAULT false,
  is_expelled       boolean NOT NULL DEFAULT false,

  -- Computed at publish time by app.compute_subject_grade()
  grade_letter      varchar(2),
  grade_point       numeric(3,2),
  component_failed  boolean NOT NULL DEFAULT false,

  entered_by        uuid REFERENCES users(id),
  entered_at        timestamptz NOT NULL DEFAULT now(),
  op_id             uuid,                            -- offline provenance
  moderated_by      uuid REFERENCES users(id),
  moderated_at      timestamptz,
  row_version       integer NOT NULL DEFAULT 1,
  UNIQUE (tenant_id, exam_subject_id, student_id)
);
