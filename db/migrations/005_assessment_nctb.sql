-- ---------------------------------------------------------------------
-- Grade + GPA computation
--
-- Bangladesh board rules encoded here:
--   1. A subject grade is F if EITHER component (CQ or MCQ) is below its own
--      pass mark, regardless of the total. This is the rule most systems get wrong.
--   2. Any F in a compulsory subject ⇒ overall GPA 0.00 and result "Fail".
--   3. The optional (4th) subject contributes only (grade_point − 2), floored at 0,
--      and is excluded from the divisor.
--   4. Final GPA is capped at 5.00.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION app.compute_subject_grade(
  p_tenant       uuid,
  p_cq           numeric, p_cq_max numeric, p_cq_pass numeric,
  p_mcq          numeric, p_mcq_max numeric, p_mcq_pass numeric,
  p_practical    numeric, p_ca numeric,
  p_total_max    numeric,
  p_is_absent    boolean,
  p_scale_id     uuid
) RETURNS TABLE (letter varchar(2), grade_point numeric, component_failed boolean)
LANGUAGE plpgsql STABLE AS $$
DECLARE
  v_total   numeric;
  v_pct     numeric;
  v_failed  boolean := false;
BEGIN
  IF p_is_absent THEN
    RETURN QUERY SELECT 'F'::varchar(2), 0.00::numeric, true;
    RETURN;
  END IF;

  -- Rule 1: component-wise pass requirement
  IF (p_cq_max  > 0 AND COALESCE(p_cq, 0)  < p_cq_pass)
  OR (p_mcq_max > 0 AND COALESCE(p_mcq, 0) < p_mcq_pass) THEN
    v_failed := true;
  END IF;

  v_total := COALESCE(p_cq,0) + COALESCE(p_mcq,0) + COALESCE(p_practical,0) + COALESCE(p_ca,0);
  v_pct   := CASE WHEN p_total_max > 0 THEN (v_total / p_total_max) * 100 ELSE 0 END;

  IF v_failed THEN
    RETURN QUERY SELECT 'F'::varchar(2), 0.00::numeric, true;
    RETURN;
  END IF;

  RETURN QUERY
    SELECT gb.letter, gb.grade_point, false
    FROM grading_bands gb
    WHERE gb.tenant_id = p_tenant
      AND gb.scale_id  = p_scale_id
      AND v_pct >= gb.min_percent AND v_pct <= gb.max_percent
    LIMIT 1;
END $$;

CREATE OR REPLACE FUNCTION app.compute_exam_gpa(p_tenant uuid, p_exam uuid, p_student uuid)
RETURNS TABLE (gpa numeric, gpa_no_optional numeric, failed_count smallint, is_pass boolean)
LANGUAGE plpgsql STABLE AS $$
DECLARE
  v_sum_compulsory numeric := 0;
  v_count_compulsory integer := 0;
  v_optional_bonus numeric := 0;
  v_failed integer := 0;
  r RECORD;
BEGIN
  FOR r IN
    SELECT em.grade_point, em.component_failed, s.is_optional,
           (e.optional_subject_id = es.subject_id) AS is_students_optional
    FROM exam_marks em
    JOIN exam_subjects es ON es.id = em.exam_subject_id
    JOIN subjects s       ON s.id  = es.subject_id
    LEFT JOIN enrolments e ON e.student_id = em.student_id
                          AND e.academic_year_id = em.academic_year_id
    WHERE em.tenant_id = p_tenant
      AND em.student_id = p_student
      AND es.exam_id = p_exam
  LOOP
    IF COALESCE(r.is_students_optional, false) THEN
      -- Rule 3: only the excess over 2.00 counts, and it never subtracts.
      v_optional_bonus := v_optional_bonus + GREATEST(COALESCE(r.grade_point,0) - 2.00, 0);
    ELSE
      v_count_compulsory := v_count_compulsory + 1;
      v_sum_compulsory := v_sum_compulsory + COALESCE(r.grade_point, 0);
      IF COALESCE(r.grade_point, 0) = 0 THEN v_failed := v_failed + 1; END IF;
    END IF;
  END LOOP;

  IF v_count_compulsory = 0 THEN
    RETURN QUERY SELECT 0.00::numeric, 0.00::numeric, 0::smallint, false;
    RETURN;
  END IF;

  -- Rule 2: any compulsory F ⇒ 0.00
  IF v_failed > 0 THEN
    RETURN QUERY SELECT 0.00::numeric,
                        round(v_sum_compulsory / v_count_compulsory, 2),
                        v_failed::smallint, false;
    RETURN;
  END IF;

  RETURN QUERY SELECT
    LEAST(round((v_sum_compulsory + v_optional_bonus) / v_count_compulsory, 2), 5.00),  -- Rule 4
    round(v_sum_compulsory / v_count_compulsory, 2),
    0::smallint,
    true;
END $$;

COMMIT;
