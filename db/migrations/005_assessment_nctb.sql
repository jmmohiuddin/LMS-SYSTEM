BEGIN;

-- ---------------------------------------------------------------------
-- Item bank
--
-- A Creative Question (সৃজনশীল প্রশ্ন) is a stimulus (উদ্দীপক) plus four
-- parts scored 1/2/3/4 against Bloom levels:
--   ক (knowledge, 1)  খ (comprehension, 2)  গ (application, 3)  ঘ (higher-order, 4)
-- Modelled as a parent question_items row + four question_item_parts rows,
-- so a school can reuse a stimulus with different part sets.
-- ---------------------------------------------------------------------
CREATE TYPE question_type   AS ENUM ('cq','mcq','short','true_false','matching','practical');
CREATE TYPE bloom_level     AS ENUM ('knowledge','comprehension','application','higher_order');
CREATE TYPE item_source     AS ENUM ('manual','sikhok_ai','board_past_paper','imported');
CREATE TYPE difficulty_band AS ENUM ('easy','medium','hard');

CREATE TABLE question_items (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id       uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  subject_id      uuid NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  class_id        uuid NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  chapter_no      smallint,
  chapter_name_bn text,
  topic           text,

  type            question_type NOT NULL,
  language        text NOT NULL DEFAULT 'bn' CHECK (language IN ('bn','en')),

  -- CQ stimulus / MCQ stem
  stem_text       text NOT NULL,
  stem_media_key  text,                             -- diagram/figure in object storage
  difficulty      difficulty_band NOT NULL DEFAULT 'medium',
  total_marks     numeric(5,2) NOT NULL DEFAULT 10,

  source          item_source NOT NULL DEFAULT 'manual',
  source_ref      text,                             -- 'Dhaka Board 2024 Q7'
  ai_session_id   uuid,                             -- provenance if generated by SikhokAI
  reviewed_by     uuid REFERENCES users(id),
  reviewed_at     timestamptz,
  is_approved     boolean NOT NULL DEFAULT false,

  -- Reuse tracking so a teacher does not repeat last term's paper
  times_used      integer NOT NULL DEFAULT 0,
  last_used_at    timestamptz,

  -- Duplicate detection + answer-leak guard (see 008)
  content_hash    bytea NOT NULL,
  embedding       vector(1024),

  created_by      uuid REFERENCES users(id),
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  deleted_at      timestamptz
);
CREATE INDEX ix_items_pick ON question_items
  (tenant_id, subject_id, class_id, chapter_no, type, difficulty)
  WHERE is_approved AND deleted_at IS NULL;
CREATE UNIQUE INDEX uq_items_hash ON question_items (tenant_id, content_hash)
  WHERE deleted_at IS NULL;
CREATE TRIGGER trg_items_tenant BEFORE INSERT OR UPDATE ON question_items
  FOR EACH ROW EXECUTE FUNCTION app.enforce_tenant();

-- CQ parts ক/খ/গ/ঘ
CREATE TABLE question_item_parts (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id     uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  item_id       uuid NOT NULL REFERENCES question_items(id) ON DELETE CASCADE,
  part_label    char(1) NOT NULL CHECK (part_label IN ('ক','খ','গ','ঘ','a','b','c','d')),
  ordinal       smallint NOT NULL CHECK (ordinal BETWEEN 1 AND 4),
  bloom         bloom_level NOT NULL,
  prompt_text   text NOT NULL,
  marks         numeric(4,2) NOT NULL CHECK (marks > 0),
  model_answer  text,
  rubric        jsonb NOT NULL DEFAULT '[]'::jsonb,  -- [{criterion, marks, descriptor}]
  UNIQUE (tenant_id, item_id, ordinal)
);
CREATE TRIGGER trg_item_parts_tenant BEFORE INSERT OR UPDATE ON question_item_parts
  FOR EACH ROW EXECUTE FUNCTION app.enforce_tenant();

-- Standard NCTB CQ mark split, enforced at the application layer and
-- documented here so nobody has to rediscover it:
COMMENT ON TABLE question_item_parts IS
  'NCTB CQ default marks: ক=1 (knowledge), খ=2 (comprehension), গ=3 (application), ঘ=4 (higher-order). '
  'Total 10 per CQ. Papers typically require answering 7 of 11 CQs = 70 marks.';

-- MCQ options
CREATE TABLE question_item_options (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id   uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  item_id     uuid NOT NULL REFERENCES question_items(id) ON DELETE CASCADE,
  ordinal     smallint NOT NULL,
  label       char(1) NOT NULL CHECK (label IN ('ক','খ','গ','ঘ','a','b','c','d')),
  option_text text NOT NULL,
  is_correct  boolean NOT NULL DEFAULT false,
  explanation text,
  UNIQUE (tenant_id, item_id, ordinal)
);
-- Exactly one correct option per MCQ.
CREATE UNIQUE INDEX uq_mcq_single_correct ON question_item_options (tenant_id, item_id)
  WHERE is_correct;
CREATE TRIGGER trg_item_opts_tenant BEFORE INSERT OR UPDATE ON question_item_options
  FOR EACH ROW EXECUTE FUNCTION app.enforce_tenant();

-- ---------------------------------------------------------------------
-- Question papers — a selected, ordered, optionally per-student randomised
-- set of items. `randomisation_seed` + student id deterministically derives
-- each student's option order, so an answer key can be regenerated later
-- without storing N copies of the paper.
-- ---------------------------------------------------------------------
CREATE TABLE question_papers (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id         uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  title_bn          text NOT NULL,
  subject_id        uuid NOT NULL REFERENCES subjects(id),
  class_id          uuid NOT NULL REFERENCES classes(id),
  total_marks       numeric(6,2) NOT NULL,
  duration_minutes  smallint NOT NULL,
  cq_answer_count   smallint,                       -- 'answer any 7 of 11'
  cq_offered_count  smallint,
  mcq_count         smallint,
  randomise_mcq_order    boolean NOT NULL DEFAULT true,
  randomise_option_order boolean NOT NULL DEFAULT true,
  randomisation_seed     bigint NOT NULL DEFAULT (random() * 9e15)::bigint,
  instructions_bn   text,
  status            text NOT NULL DEFAULT 'draft'
                      CHECK (status IN ('draft','finalised','used','archived')),
  created_by        uuid REFERENCES users(id),
  created_at        timestamptz NOT NULL DEFAULT now()
);
CREATE TRIGGER trg_papers_tenant BEFORE INSERT OR UPDATE ON question_papers
  FOR EACH ROW EXECUTE FUNCTION app.enforce_tenant();

