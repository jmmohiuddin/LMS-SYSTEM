CREATE OR REPLACE FUNCTION app.block_published_mark_update() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE published boolean;
BEGIN
  SELECT e.status = 'published' INTO published
  FROM exam_subjects es JOIN exams e ON e.id = es.exam_id
  WHERE es.id = NEW.exam_subject_id;

  IF published AND NEW.moderated_by IS NULL THEN
    RAISE EXCEPTION 'published marks are immutable; file a mark_correction'
      USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_marks_immutable BEFORE UPDATE OF cq_marks, mcq_marks, practical_marks, ca_marks
  ON exam_marks FOR EACH ROW EXECUTE FUNCTION app.block_published_mark_update();

